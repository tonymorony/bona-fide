// Writes src/abi.ts from the contracts' Foundry artifacts, so the ABIs can't drift from the Solidity:
//
//   forge build    (in contracts/)
//   npm run abi    (in sdk/)
//
// test/abi.test.ts fails while src/abi.ts differs from what this would write.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";

const OUT = fileURLToPath(new URL("../../contracts/out/", import.meta.url));
export const ABI_MODULE = fileURLToPath(new URL("../src/abi.ts", import.meta.url));

/** Each exported ABI, the contract it comes from, and what it is. */
const CONTRACTS = [
  ["escrowAbi", "BonaFideEscrow", "The escrow: holds each Deposit until a Refund or a Forfeit."],
  ["routerAbi", "CharityRouter", "The Forfeit sink: sends forfeited USDC through CCTP to one fixed recipient."],
  [
    "bountyFactoryAbi",
    "BountyWalletFactory",
    "Creates one Bounty wallet per repo and owner, at a predictable address.",
  ],
  ["bountyWalletAbi", "BountyWallet", "A Maintainer's Bounty wallet: holds a repo's budget and pays its Bounties."],
] as const;

export async function renderAbiModule(): Promise<string> {
  const parts = ["// Generated by scripts/abi.ts from the Foundry artifacts. Don't edit: run `npm run abi`.\n"];
  for (const [name, contract, about] of CONTRACTS) {
    const { abi } = JSON.parse(await readFile(`${OUT}${contract}.sol/${contract}.json`, "utf8")) as { abi: unknown };
    parts.push(`/** ${about} */\nexport const ${name} = ${JSON.stringify(abi)} as const;\n`);
  }
  const options = await resolveConfig(ABI_MODULE);
  return format(parts.join("\n"), { ...options, filepath: ABI_MODULE });
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await writeFile(ABI_MODULE, await renderAbiModule());
  console.log(`Wrote ${ABI_MODULE}`);
}
